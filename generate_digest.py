def merge_sessions(
    index_sessions: list[dict],
    jsonl_sessions: list[dict],
    dt_sessions: list[dict],
    since: Optional[str],
) -> list[dict]:
    """
    Merge sessions from all three sources with deduplication.

    Priority:
    1. JSONL sessions (have session IDs, most accurate)
    2. Index sessions (non-stale only — already filtered by load_sessions)
    3. Day-tracker sessions (only for projects not covered by JSONL or index)
    """
    merged: list[dict] = []
    seen_ids: set[str] = set()

    # Projects covered by JSONL or index (by projectPath)
    covered_paths: set[str] = set()

    # 1. Add JSONL sessions
    for s in jsonl_sessions:
        sid = s.get("sessionId")
        if sid:
            if sid in seen_ids:
                continue
            seen_ids.add(sid)
        merged.append(s)
        covered_paths.add(s.get("projectPath", ""))

    # 2. Add index sessions (non-stale, already filtered)
    for s in index_sessions:
        sid = s.get("sessionId")
        if sid:
            if sid in seen_ids:
                continue
            seen_ids.add(sid)
        merged.append(s)
        covered_paths.add(s.get("projectPath", ""))

    # 3. Add day-tracker sessions only for uncovered projects
    dt_added = 0
    for s in dt_sessions:
        if s.get("projectPath", "") in covered_paths:
            continue  # Already have JSONL or index data for this project
        merged.append(s)
        dt_added += 1

    if dt_added:
        print(f"Merge: added {dt_added} day-tracker sessions for uncovered projects", file=sys.stderr)

    return merged


