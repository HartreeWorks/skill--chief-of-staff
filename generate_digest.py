def generate_draft_digest(groups: dict, period_from: Optional[str]) -> dict:
    """Generate a draft digest with placeholders for narrative content."""
    now = datetime.now(timezone.utc).astimezone()
    now_iso = now.isoformat()

    total_chats = sum(len(g["sessions"]) for g in groups.values())

    by_project = {}
    for project_name, group in groups.items():
        sessions = group["sessions"]
        session_summaries = [s["summary"] for s in sessions if s["summary"]]

        # For sessions without summaries, fall back to firstPrompt
        if not session_summaries:
            session_summaries = [s["firstPrompt"] for s in sessions if s.get("firstPrompt")]

        claude_count = sum(1 for s in sessions if s.get("source") in ("claude", "claude-jsonl"))
        codex_count = sum(1 for s in sessions if s.get("source") == "codex")
        dt_count = sum(1 for s in sessions if s.get("source") == "day-tracker")

        # Collect recent turns across all sessions for this project
        all_user_turns = []
        all_assistant_turns = []
        for s in sessions:
            all_user_turns.extend(s.get("recentUserTurns") or [])
            all_assistant_turns.extend(s.get("recentAssistantTurns") or [])

        by_project[project_name] = {
            "type": group["type"],
            "chat_count": len(sessions),
            "claude_count": claude_count,
            "codex_count": codex_count,
            "day_tracker_count": dt_count,
            "combined_summary": (
                f"[{len(sessions)} sessions - summarise based on: {'; '.join(session_summaries[:5])}]"
                if session_summaries
                else f"[{len(sessions)} sessions - no summaries available]"
            ),
            "all_tasks_completed": [],
            "all_tasks_in_progress": [],
            "all_blockers": [],
            "_session_summaries": session_summaries,
            "_recent_user_turns": all_user_turns,
            "_recent_assistant_turns": all_assistant_turns,
        }

    return {
        "generated": now_iso,
        "period": {
            "from": period_from or "unknown",
            "to": now_iso,
        },
        "chat_count": total_chats,
        "by_project": by_project,
        "key_completions": ["[To be filled by Claude based on session summaries]"],
        "still_in_progress": ["[To be filled by Claude based on session summaries]"],
        "all_blockers": ["[To be filled by Claude based on session summaries]"],
    }


def save_digest(digest: dict, date: str) -> Path:
    """Save the digest to a file. Returns the file path."""
    DIGESTS_DIR.mkdir(parents=True, exist_ok=True)
    output_path = DIGESTS_DIR / f"{date}.json"

    with open(output_path, "w") as f:
        json.dump(digest, f, indent=2)

    return output_path


