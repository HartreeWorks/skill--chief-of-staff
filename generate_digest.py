def find_codex_session_files(since: Optional[str] = None) -> list[Path]:
    """Find Codex session JSONL files, optionally filtered by date."""
    if not CODEX_SESSIONS_DIR.exists():
        return []

    if since:
        try:
            since_date = parse_timestamp(since).date()
        except ValueError:
            since_date = None
    else:
        since_date = None

    files = []
    for year_dir in sorted(CODEX_SESSIONS_DIR.iterdir()):
        if not year_dir.is_dir() or not year_dir.name.isdigit():
            continue
        for month_dir in sorted(year_dir.iterdir()):
            if not month_dir.is_dir() or not month_dir.name.isdigit():
                continue
            for day_dir in sorted(month_dir.iterdir()):
                if not day_dir.is_dir() or not day_dir.name.isdigit():
                    continue
                if since_date:
                    try:
                        dir_date = datetime(
                            int(year_dir.name), int(month_dir.name), int(day_dir.name)
                        ).date()
                        if dir_date < since_date:
                            continue
                    except ValueError:
                        continue
                for f in sorted(day_dir.glob("rollout-*.jsonl")):
                    files.append(f)
    return files


def load_codex_sessions(paths: list[Path]) -> list[dict]:
    """Load session metadata from Codex JSONL files."""
    sessions = []
    for path in paths:
        try:
            with open(path) as f:
                for line in f:
                    data = json.loads(line)
                    if data.get("type") == "session_meta":
                        payload = data["payload"]
                        # Extract first user prompt for context
                        first_prompt = ""
                        f.seek(0)
                        for inner_line in f:
                            item = json.loads(inner_line)
                            if item.get("type") == "response_item":
                                p = item.get("payload", {})
                                if p.get("role") == "user":
                                    for c in p.get("content", []):
                                        text = c.get("text", "")
                                        # Skip system instructions
                                        if text.startswith("# ") or text.startswith("<INSTRUCTIONS>"):
                                            continue
                                        if len(text) > 10:
                                            first_prompt = text[:200]
                                            break
                                if first_prompt:
                                    break

                        sessions.append({
                            "sessionId": payload.get("id", ""),
                            "projectPath": payload.get("cwd", ""),
                            "created": payload.get("timestamp", ""),
                            "modified": data.get("timestamp", ""),
                            "summary": "",
                            "firstPrompt": first_prompt,
                            "messageCount": 0,
                            "_source_file": str(path),
                            "_source": "codex",
                        })
                        break  # Only need session_meta
        except (json.JSONDecodeError, OSError) as e:
            print(f"Warning: Could not load Codex session {path}: {e}", file=sys.stderr)
    return sessions


