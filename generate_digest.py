"""
Generate Claude Code + Codex chat digests with guaranteed file saving.

Session discovery — priority order:
  1. JSONL scan: reads ~/.claude/projects/*/*.jsonl directly (always current)
  2. Day-tracker daily JSONs: ~/Documents/day-tracker/data/daily/YYYY-MM-DD.json
     — canonical time-based confirmation of which sessions were active
     — fills projects not covered by JSONL scan
  3. sessions-index.json: legacy fallback, only when non-stale entries exist

Deterministic parts (script handles):
- Finding sessions across all projects (Claude Code + Codex)
- Loading last digest to get period.to timestamp
- Filtering sessions by timestamp
- Grouping by project
- Calculating session counts
- Extracting session summaries
- SAVING THE FILE (guaranteed - can't be forgotten)

Judgment parts (Claude can enhance after):
- Writing narrative combined_summary for each project
- Identifying key_completions, still_in_progress, all_blockers
"""

