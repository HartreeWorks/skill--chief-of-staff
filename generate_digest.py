def get_last_digest() -> Optional[dict]:
    """Get the most recent digest with its period.to timestamp."""
    if not DIGESTS_DIR.exists():
        return None

    digest_files = sorted(DIGESTS_DIR.glob("*.json"), reverse=True)
    for digest_file in digest_files:
        try:
            with open(digest_file) as f:
                data = json.load(f)
                if "period" in data and "to" in data["period"]:
                    data["_file"] = str(digest_file)
                    return data
        except (json.JSONDecodeError, OSError):
            continue
    return None


