def extract_jsonl_metadata(jsonl_path: Path) -> Optional[dict]:
    """
    Extract session metadata from a JSONL file by reading up to 50 lines.

    Handles two formats:
    - Newer: starts with file-history-snapshot, then progress line with cwd/sessionId
    - Older: starts with queue-operation (sessionId, timestamp)
    """
    session_id = None
    project_path = None
    created = None
    first_prompt = None

    try:
        with open(jsonl_path, encoding="utf-8", errors="replace") as f:
            for i, raw_line in enumerate(f):
                if i >= 50:
                    break
                try:
                    obj = json.loads(raw_line)
                except json.JSONDecodeError:
                    continue

                obj_type = obj.get("type", "")

                # Pick up sessionId from queue-operation or any line that has it
                if session_id is None and obj.get("sessionId"):
                    session_id = obj["sessionId"]

                # Pick up cwd (projectPath) from progress/user/assistant lines
                if project_path is None and obj.get("cwd"):
                    project_path = obj["cwd"]

                # Pick up created timestamp
                if created is None:
                    if obj_type == "queue-operation" and obj.get("timestamp"):
                        created = obj["timestamp"]
                    elif obj.get("timestamp") and project_path:
                        # Use first timestamped line after we have context
                        created = obj["timestamp"]

                # Pick up first user prompt (skip system messages)
                if first_prompt is None and obj_type == "user":
                    msg = obj.get("message", {})
                    content = msg.get("content", [])
                    if isinstance(content, list):
                        for part in content:
                            if not isinstance(part, dict):
                                continue
                            text = part.get("text", "")
                            # Skip system instructions and very short texts
                            if text.startswith("#") or text.startswith("<") or len(text) < 10:
                                continue
                            first_prompt = text[:200]
                            break
                    elif isinstance(content, str) and len(content) >= 10:
                        if not content.startswith("#") and not content.startswith("<"):
                            first_prompt = content[:200]

                # Stop early once we have everything
                if session_id and project_path and created and first_prompt:
                    break

    except OSError as e:
        print(f"Warning: Could not read {jsonl_path}: {e}", file=sys.stderr)
        return None

    # Need at least a project path to be useful
    if not project_path:
        return None

    # Fallback: use file mtime as created if we couldn't find a timestamp
    if not created:
        created = mtime_dt(jsonl_path).isoformat()

    # Use file mtime as modified (always reliable)
    modified = mtime_dt(jsonl_path).isoformat()

    # Extract recent turns from the tail of the file
    turns = extract_session_turns(jsonl_path)

    return {
        "sessionId": session_id,
        "projectPath": project_path,
        "created": created,
        "modified": modified,
        "summary": "",
        "firstPrompt": first_prompt or "",
        "recentUserTurns": turns["recentUserTurns"],
        "recentAssistantTurns": turns["recentAssistantTurns"],
        "_source_file": str(jsonl_path),
        "_source": "claude-jsonl",
    }


def scan_jsonl_sessions(since: Optional[str]) -> list[dict]:
    """
    Scan ~/.claude/projects/*/*.jsonl directly for session metadata.

    For each project directory:
    - Skips if a non-stale sessions-index.json exists (legacy path handles it)
    - Otherwise reads *.jsonl files modified after `since`
    """
    if not PROJECTS_DIR.exists():
        return []

    since_dt = parse_timestamp(since) if since else None
    sessions = []
    seen_ids: set[str] = set()

    for project_dir in sorted(PROJECTS_DIR.iterdir()):
        if not project_dir.is_dir():
            continue

        # Skip if this project has a non-stale sessions-index.json
        index_path = project_dir / "sessions-index.json"
        if index_path.exists():
            try:
                index_data = json.loads(index_path.read_text())
                if not index_is_stale(index_data, since):
                    continue  # Non-stale index; legacy path handles this project
            except (json.JSONDecodeError, OSError):
                pass  # Corrupt index — fall through to JSONL scan

        # Scan JSONL files in this directory
        for jsonl_path in sorted(project_dir.glob("*.jsonl")):
            # mtime pre-filter: skip files not touched since the cutoff
            if since_dt and mtime_dt(jsonl_path) <= since_dt:
                continue

            session = extract_jsonl_metadata(jsonl_path)
            if not session:
                continue

            # Deduplicate by sessionId
            sid = session.get("sessionId")
            if sid:
                if sid in seen_ids:
                    continue
                seen_ids.add(sid)

            sessions.append(session)

    print(f"JSONL scan: {len(sessions)} sessions from direct file scan", file=sys.stderr)
    return sessions


