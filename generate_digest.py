def load_sessions_from_day_tracker(since: Optional[str]) -> list[dict]:
    """
    Load Claude Code sessions from day-tracker daily JSON files.

    Day-tracker captures active Claude Code sessions every ~5 minutes.
    We deduplicate by (project_path, title) to get one entry per unique session per day.

    Only includes projects NOT already covered by JSONL scan or non-stale index
    (caller handles filtering via covered_projects set).
    """
    if not DAY_TRACKER_DAILY_DIR.exists():
        print("Day-tracker daily dir not found; skipping", file=sys.stderr)
        return []

    since_dt = parse_timestamp(since) if since else None
    # Key: (project_path, title) → session dict
    seen: dict[tuple, dict] = {}

    daily_files = sorted(DAY_TRACKER_DAILY_DIR.glob("*.json"))
    for daily_file in daily_files:
        try:
            date_str = daily_file.stem  # e.g. "2026-03-08"
            # Skip sync-conflict files and other non-date filenames
            if len(date_str) != 10:
                continue
            # Quick date-based pre-filter (file date < since date → skip)
            if since_dt:
                file_date = datetime.strptime(date_str, "%Y-%m-%d").replace(tzinfo=_CET)
                if file_date.date() < since_dt.date():
                    continue

            data = json.loads(daily_file.read_text())
            entries = data.get("entries", [])

            for entry in entries:
                entry_ts_str = entry.get("timestamp", "")
                if not entry_ts_str:
                    continue

                # Day-tracker timestamps are naive local; parse_timestamp adds CET offset
                try:
                    entry_ts = parse_timestamp(entry_ts_str)
                except ValueError:
                    continue

                if since_dt and entry_ts <= since_dt:
                    continue

                active_sessions = entry.get("active_sessions") or []
                for sess in active_sessions:
                    if sess.get("agent") != "claude":
                        continue

                    project_path = sess.get("project_path", "")
                    title = sess.get("title", "")
                    key = (project_path, title)

                    if key not in seen:
                        seen[key] = {
                            "sessionId": None,
                            "projectPath": project_path,
                            "created": entry_ts_str,
                            "modified": entry_ts_str,
                            "summary": title,
                            "firstPrompt": "",
                            "_source_file": str(daily_file),
                            "_source": "day-tracker",
                        }
                    else:
                        seen[key]["modified"] = entry_ts_str

        except (json.JSONDecodeError, OSError, ValueError) as e:
            print(f"Warning: Could not read day-tracker file {daily_file}: {e}", file=sys.stderr)

    sessions = list(seen.values())
    print(f"Day-tracker: {len(sessions)} unique sessions from daily logs", file=sys.stderr)
    return sessions


