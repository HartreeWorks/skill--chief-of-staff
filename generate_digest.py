def index_is_stale(index_data: dict, since: Optional[str]) -> bool:
    """Return True if the index has no entries newer than `since`."""
    if not since:
        return False
    entries = index_data.get("entries", [])
    if not entries:
        return True
    since_dt = parse_timestamp(since)
    for e in entries:
        ts = e.get("modified") or e.get("created", "")
        if ts:
            try:
                if parse_timestamp(ts) > since_dt:
                    return False
            except ValueError:
                pass
    return True


def find_session_files() -> list[Path]:
    """Find all sessions-index.json files in ~/.claude/projects/."""
    return list(PROJECTS_DIR.glob("*/sessions-index.json"))


def load_sessions(paths: list[Path], since: Optional[str] = None) -> list[dict]:
    """Load non-stale session entries from sessions-index.json files."""
    all_sessions = []
    for path in paths:
        try:
            with open(path) as f:
                data = json.load(f)
            if since and index_is_stale(data, since):
                continue
            entries = data.get("entries", [])
            for entry in entries:
                entry["_source_file"] = str(path)
                entry["_source"] = "claude"
            all_sessions.extend(entries)
        except (json.JSONDecodeError, OSError) as e:
            print(f"Warning: Could not load {path}: {e}", file=sys.stderr)
    return all_sessions


