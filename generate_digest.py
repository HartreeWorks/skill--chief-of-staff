def _collect_all_sessions(period_from: Optional[str]) -> tuple[list[dict], list[dict]]:
    """
    Collect all sessions from all sources, merged and filtered.

    Returns (claude_sessions, codex_sessions) — already filtered by period_from.
    """
    # Source 1: JSONL scan (primary)
    jsonl_sessions = scan_jsonl_sessions(period_from)

    # Source 3: sessions-index.json (legacy, non-stale only)
    index_files = find_session_files()
    index_sessions = load_sessions(index_files, since=period_from)

    # Source 2: day-tracker (supplementary)
    dt_sessions = load_sessions_from_day_tracker(period_from)

    # Merge
    claude_sessions = merge_sessions(index_sessions, jsonl_sessions, dt_sessions, period_from)

    # Codex sessions (unchanged)
    codex_files = find_codex_session_files(period_from)
    codex_sessions = load_codex_sessions(codex_files)

    return claude_sessions, codex_sessions


def get_status() -> dict:
    """Get current status without generating a digest."""
    last_digest = get_last_digest()
    period_from = last_digest["period"]["to"] if last_digest else None

    claude_sessions, codex_sessions = _collect_all_sessions(period_from)
    all_combined = claude_sessions + codex_sessions
    new_sessions = filter_sessions(all_combined, period_from)

    today = datetime.now().strftime("%Y-%m-%d")
    today_digest_exists = (DIGESTS_DIR / f"{today}.json").exists()

    # Breakdown by source
    source_counts: dict[str, int] = {}
    for s in new_sessions:
        src = s.get("_source", "unknown")
        source_counts[src] = source_counts.get(src, 0) + 1

    return {
        "last_digest_date": last_digest["_file"].split("/")[-1].replace(".json", "") if last_digest else None,
        "last_digest_period_to": period_from,
        "total_sessions_found": len(all_combined),
        "sessions_since_last_digest": len(new_sessions),
        "sessions_by_source": source_counts,
        "projects_with_new_sessions": len(group_by_project(new_sessions)),
        "today_digest_exists": today_digest_exists,
    }


def main():
    parser = argparse.ArgumentParser(
        description="Generate Claude Code + Codex chat digests with guaranteed file saving."
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Output JSON to stdout (for Claude to read and enhance)",
    )
    parser.add_argument(
        "--status",
        action="store_true",
        help="Check status without generating",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Force regenerate even if today's digest exists",
    )

    args = parser.parse_args()

    # Status mode
    if args.status:
        status = get_status()
        if args.json:
            print(json.dumps(status, indent=2))
        else:
            print(f"Last digest:      {status['last_digest_date'] or 'None'}")
            print(f"Period ends:      {status['last_digest_period_to'] or 'N/A'}")
            print(f"Sessions found:   {status['total_sessions_found']}")
            print(f"  by source:      {status['sessions_by_source']}")
            print(f"Since cutoff:     {status['sessions_since_last_digest']}")
            print(f"Projects active:  {status['projects_with_new_sessions']}")
            print(f"Today's digest:   {'exists' if status['today_digest_exists'] else 'missing'}")
        return

    # Check if today's digest already exists
    today = datetime.now().strftime("%Y-%m-%d")
    today_path = DIGESTS_DIR / f"{today}.json"

    if today_path.exists() and not args.force:
        print(f"Today's digest already exists: {today_path}")
        print("Use --force to regenerate.")
        return

    # Generate the digest
    last_digest = get_last_digest()
    period_from = last_digest["period"]["to"] if last_digest else None

    claude_sessions, codex_sessions = _collect_all_sessions(period_from)
    print(f"Loaded {len(claude_sessions)} Claude sessions (all sources)", file=sys.stderr)
    print(f"Loaded {len(codex_sessions)} Codex sessions", file=sys.stderr)

    all_combined = claude_sessions + codex_sessions
    new_sessions = filter_sessions(all_combined, period_from)
    print(f"Filtered to {len(new_sessions)} sessions since {period_from or 'beginning'}", file=sys.stderr)

    groups = group_by_project(new_sessions)
    print(f"Grouped into {len(groups)} projects", file=sys.stderr)

    digest = generate_draft_digest(groups, period_from)

    if args.json:
        print(json.dumps(digest, indent=2))
    else:
        output_path = save_digest(digest, today)
        print(f"Saved digest to: {output_path}")
        print(f"Chat count: {digest['chat_count']}")
        print(f"Projects: {', '.join(groups.keys())}")
        print("\nNote: combined_summary fields contain placeholders. Claude can enhance these.")


if __name__ == "__main__":
    main()
