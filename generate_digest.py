# Fixed CET offset (UTC+1) used for naive day-tracker timestamps
# Acceptable approximation; off by 1h during CEST (late Mar–late Oct)
_CET = timezone(timedelta(hours=1))


# ---------------------------------------------------------------------------
# Timestamp helpers
# ---------------------------------------------------------------------------

def parse_timestamp(ts: str) -> datetime:
    """Parse an ISO timestamp string to timezone-aware datetime."""
    if ts.endswith("Z"):
        ts = ts[:-1] + "+00:00"
    dt = datetime.fromisoformat(ts)
    if dt.tzinfo is None:
        # Treat naive timestamps as CET (day-tracker local time)
        dt = dt.replace(tzinfo=_CET)
    return dt


def mtime_dt(path: Path) -> datetime:
    """Return file modification time as timezone-aware UTC datetime."""
    return datetime.fromtimestamp(path.stat().st_mtime, tz=timezone.utc)


# ---------------------------------------------------------------------------
# JSONL turn extraction (adapted from agent-conversations script)
# ---------------------------------------------------------------------------

_XML_TAG_RE = re.compile(r"<[^>]+>")
_WHITESPACE_RE = re.compile(r"\s+")
_IGNORE_PREFIXES = (
    "Caveat: The messages below were generated by the user while running local commands",
    "# AGENTS.md instructions",
    "<environment_context>",
)
_MAX_TURN_CHARS = 280
_MAX_USER_TURNS = 4
_MAX_ASSISTANT_TURNS = 3


def _normalize_text(text: str) -> str:
    """Clean up turn text: strip XML tags, collapse whitespace, truncate."""
    if not text or not isinstance(text, str):
        return ""
    cleaned = _XML_TAG_RE.sub("", text)
    cleaned = _WHITESPACE_RE.sub(" ", cleaned).strip()
    if not cleaned or any(cleaned.startswith(p) for p in _IGNORE_PREFIXES):
        return ""
    return cleaned[:_MAX_TURN_CHARS]


def _extract_user_text(entry: dict) -> str:
    """Extract user message text from a JSONL entry."""
    msg = entry.get("message")
    if isinstance(msg, str):
        return _normalize_text(msg)
    if not isinstance(msg, dict):
        return ""
    content = msg.get("content", "")
    if isinstance(content, str):
        return _normalize_text(content)
    if isinstance(content, list):
        for block in content:
            if not isinstance(block, dict) or block.get("type") != "text":
                continue
            text = _normalize_text(block.get("text", ""))
            if text:
                return text
    return ""


def _extract_assistant_text(entry: dict) -> str:
    """Extract assistant message text from a JSONL entry."""
    msg = entry.get("message")
    if not isinstance(msg, dict):
        return ""
    content = msg.get("content", [])
    if not isinstance(content, list):
        return ""
    parts = []
    for block in content:
        if not isinstance(block, dict) or block.get("type") != "text":
            continue
        cleaned = _normalize_text(block.get("text", ""))
        if cleaned:
            parts.append(cleaned)
    return " ".join(parts).strip()[:_MAX_TURN_CHARS]


def _append_turn(items: list, text: str, limit: int) -> None:
    """Append a turn to the list, deduplicating and capping length."""
    if not text or (items and items[-1] == text):
        return
    items.append(text)
    if len(items) > limit:
        del items[: len(items) - limit]


def extract_session_turns(jsonl_path: Path, max_bytes: int = 100_000) -> dict:
    """
    Read the tail of a JSONL session file and extract recent user/assistant turns.

    Returns {"recentUserTurns": [...], "recentAssistantTurns": [...]}.
    """
    user_turns: list[str] = []
    assistant_turns: list[str] = []

    try:
        file_size = os.path.getsize(jsonl_path)
        with open(jsonl_path, encoding="utf-8", errors="replace") as f:
            if file_size > max_bytes:
                f.seek(file_size - max_bytes)
                f.readline()  # skip partial first line
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    entry = json.loads(line)
                except json.JSONDecodeError:
                    continue

                entry_type = entry.get("type")
                if entry_type == "user":
                    _append_turn(user_turns, _extract_user_text(entry), _MAX_USER_TURNS)
                elif entry_type == "assistant":
                    _append_turn(assistant_turns, _extract_assistant_text(entry), _MAX_ASSISTANT_TURNS)
    except OSError:
        pass

    return {
        "recentUserTurns": user_turns,
        "recentAssistantTurns": assistant_turns,
    }


