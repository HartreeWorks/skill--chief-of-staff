def filter_sessions(sessions: list[dict], since: Optional[str]) -> list[dict]:
    """Filter sessions created or modified after the given timestamp."""
    if not since:
        return sessions

    since_dt = parse_timestamp(since)
    filtered = []
    for session in sessions:
        # For day-tracker sessions, use modified (last seen); for others, use created
        source = session.get("_source", "")
        if source == "day-tracker":
            ts_str = session.get("modified") or session.get("created")
        else:
            ts_str = session.get("created") or session.get("modified")

        if ts_str:
            try:
                ts_dt = parse_timestamp(ts_str)
                if ts_dt > since_dt:
                    filtered.append(session)
            except ValueError:
                filtered.append(session)  # Include on parse error (conservative)
        else:
            filtered.append(session)  # Include if no timestamp (conservative)
    return filtered


def get_project_name(project_path: str) -> str:
    """Extract a readable project name from the projectPath."""
    if not project_path:
        return "Unknown"

    path = Path(project_path)

    # Handle ~/.claude/skills/ paths
    if ".claude/skills" in project_path:
        parts = project_path.split(".claude/skills/")
        if len(parts) > 1:
            skill_name = parts[1].split("/")[0]
            return f"Skills ({skill_name})"
        return "Skills"

    # Handle ~/.agents/skills/ paths
    if ".agents/skills" in project_path:
        parts = project_path.split(".agents/skills/")
        if len(parts) > 1:
            skill_name = parts[1].split("/")[0]
            return f"Skills ({skill_name})"
        return "Skills"

    # Handle ~/.claude/ paths
    if ".claude" in project_path and "skills" not in project_path:
        return "Claude Code config"

    # Handle ~/.agents/ paths (not skills)
    if ".agents" in project_path and "skills" not in project_path:
        return ".agents"

    # Use the last meaningful path component
    name = path.name
    if not name or name in [".", ".."]:
        name = path.parent.name

    return name or "Unknown"


def categorise_project(project_path: str, project_name: str) -> str:
    """Determine the project type (client, personal, tools, planning, other)."""
    path_lower = project_path.lower() if project_path else ""

    # Skills and config are tools
    if ".claude" in path_lower or ".agents" in path_lower:
        return "tools"

    # Planning projects
    if "plans-and-reviews" in path_lower or "planning" in project_name.lower():
        return "planning"

    # Client projects often have a year-month prefix like "2025-09-".
    if "/Documents/Projects/" in project_path:
        folder = Path(project_path).name
        if re.match(r"^\d{4}-\d{2}-", folder):
            return "client"

    return "personal"


def group_by_project(sessions: list[dict]) -> dict:
    """Group sessions by project with raw summaries."""
    groups = {}

    for session in sessions:
        project_path = session.get("projectPath", "")
        project_name = get_project_name(project_path)

        if project_name not in groups:
            groups[project_name] = {
                "type": categorise_project(project_path, project_name),
                "project_path": project_path,
                "sessions": [],
            }

        groups[project_name]["sessions"].append({
            "sessionId": session.get("sessionId"),
            "summary": session.get("summary", ""),
            "firstPrompt": session.get("firstPrompt", "")[:200],
            "recentUserTurns": session.get("recentUserTurns", []),
            "recentAssistantTurns": session.get("recentAssistantTurns", []),
            "created": session.get("created"),
            "modified": session.get("modified"),
            "messageCount": session.get("messageCount", 0),
            "source": session.get("_source", "claude"),
        })

    return groups


